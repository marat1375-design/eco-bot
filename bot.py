@bot.message_handler(content_types=["photo"])
def handle_photo(message):
    wait_msg = bot.send_message(message.chat.id, "Анализирую фото по экологическому блоку...")

    try:
        file_id = message.photo[-1].file_id
        file_info = bot.get_file(file_id)
        file_url = (
            f"https://api.telegram.org/file/bot{os.environ['TELEGRAM_TOKEN']}/{file_info.file_path}"
        )

        photo_bytes = requests.get(file_url, timeout=30).content
        photo_b64 = base64.b64encode(photo_bytes).decode("utf-8")
        caption = message.caption or ""

        model = genai.GenerativeModel(SELECTED_MODEL)

        # Шаг 1: описание фото
        photo_response = model.generate_content([
            PHOTO_PROMPT + f"\n\nПодпись пользователя: {caption}",
            {"mime_type": "image/jpeg", "data": photo_b64}
        ])
        photo_description = clean_answer(photo_response.text)

        if "явное экологическое замечание не выявлено" in photo_description.lower() and not caption:
            bot.delete_message(message.chat.id, wait_msg.message_id)
            bot.send_message(message.chat.id, photo_description)
            return

        # Шаг 2: анализ по локальному контексту
        query = photo_description + " " + caption
        context = build_context(query)

        if not context:
            bot.delete_message(message.chat.id, wait_msg.message_id)
            bot.send_message(
                message.chat.id,
                "По фото экологическое замечание не определено, "
                "либо тема не относится к экологическому блоку текущей версии."
            )
            return

        full_query = (
            SYSTEM_PROMPT
            + "\n\n=== ФРАГМЕНТЫ ИЗ НОРМАТИВНЫХ ИСТОЧНИКОВ ===\n"
            + context
            + "\n\n=== ОПИСАНИЕ ФОТО ===\n"
            + photo_description
            + "\n\n=== ПОДПИСЬ ПОЛЬЗОВАТЕЛЯ ===\n"
            + caption
        )

        response = model.generate_content(full_query)
        answer = clean_answer(response.text)

        bot.delete_message(message.chat.id, wait_msg.message_id)
        bot.send_message(message.chat.id, "На фото: " + photo_description)
        send_long_message(message.chat.id, answer)

    except Exception as error:
        try:
            bot.edit_message_text("Ошибка: " + str(error), message.chat.id, wait_msg.message_id)
        except Exception:
            bot.send_message(message.chat.id, "Ошибка: " + str(error))


@bot.message_handler(func=lambda message: True)
def handle_text(message):
    user_text = message.text or ""
    wait_msg = bot.send_message(message.chat.id, "Подбираю нормативные требования...")

    try:
        if not is_ecology_query(user_text):
            bot.edit_message_text(
                "В текущей версии анализируются только экологические замечания "
                "по Экологическому кодексу РК и КоАП РК.",
                message.chat.id,
                wait_msg.message_id
            )
            return

        context = build_context(user_text)

        if not context:
            bot.edit_message_text(
                "Не удалось подобрать нормативные требования по вашему запросу. "
                "Попробуйте описать экологическое замечание подробнее.",
                message.chat.id,
                wait_msg.message_id
            )
            return

        model = genai.GenerativeModel(SELECTED_MODEL)

        full_query = (
            SYSTEM_PROMPT
            + "\n\n=== ФРАГМЕНТЫ ИЗ НОРМАТИВНЫХ ИСТОЧНИКОВ ===\n"
            + context
            + "\n\n=== ЗАПРОС ПОЛЬЗОВАТЕЛЯ ===\n"
            + user_text
        )

        response = model.generate_content(full_query)
        answer = clean_answer(response.text)

        bot.delete_message(message.chat.id, wait_msg.message_id)
        send_long_message(message.chat.id, answer)

    except Exception as error:
        try:
            bot.edit_message_text("Ошибка: " + str(error), message.chat.id, wait_msg.message_id)
        except Exception:
            bot.send_message(message.chat.id, "Ошибка: " + str(error))


