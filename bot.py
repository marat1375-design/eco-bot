def detect_topics(text: str) -> set:
    """Определяет активные темы по тексту запроса."""
    text_lower = text.lower()
    active = set()
    for topic, keywords in TOPIC_GROUPS.items():
        if any(kw in text_lower for kw in keywords):
            active.add(topic)
    return active


def select_articles(query: str) -> list:
    """Отбирает релевантные статьи из локальной базы по тексту запроса."""
    text_lower = query.lower()
    selected = []
    seen_numbers_laws = set()

    for article in ARTICLES:
        key = (article["law"], article["number"])
        if key in seen_numbers_laws:
            continue
        score = sum(1 for tag in article["tags"] if tag in text_lower)
        if score > 0:
            selected.append((score, article))
            seen_numbers_laws.add(key)

    # Сортируем по релевантности, возвращаем топ-10
    selected.sort(key=lambda x: x[0], reverse=True)
    return [a for _, a in selected[:10]]


