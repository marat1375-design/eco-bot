FALLBACK_URLS = {
    "ecocode": "https://adilet.zan.kz/rus/docs/K2100000400",
}

FALLBACK_HEADERS = {
    "User-Agent": (
        "Mozilla/5.0 (Windows NT 10.0; Win64; x64) "
        "AppleWebKit/537.36 (KHTML, like Gecko) "
        "Chrome/120.0 Safari/537.36"
    )
}

# Статьи, запрещённые в резерве
_FALLBACK_BAD  = {"3", "4", "350"}
_FALLBACK_NEDRA = {"397"}
_NEDRA_WORDS   = ["недр", "скважин", "бурен", "буров", "добыч", "месторожден", "углеводород"]


def _fallback_article_number(block: str):
    m = re.search(r"Статья\s+(\d+)", block.strip())
    return m.group(1) if m else None


def _fallback_score(block: str, query: str, law_key: str) -> int:
    bl = block.lower()
    ql = query.lower()
    words = set(re.findall(r"[а-яёА-ЯЁ]{4,}", ql))
    score = sum(2 for w in words if w in bl)
    strong = [
        "запрещ", "обязан", "не допускается", "должны", "требования",
        "загрязнен", "отход", "накопление", "раздельный", "захоронен",
        "земель", "почв", "вод", "сброс", "атмосфер", "выброс",
        "рекультивац", "учет",
    ]
    score += sum(3 for t in strong if t in bl)
    if law_key == "ecocode":
        if "цель" in bl and "задач" in bl:
            score -= 25
        if "принцип" in bl:
            score -= 15
    return score


def _fetch_fallback(law_key: str, query: str, limit: int = 4) -> str:
    """Парсит adilet.zan.kz и возвращает до limit наиболее релевантных статей."""
    url = FALLBACK_URLS[law_key]
    ql = query.lower()
    try:
        resp = requests.get(url, headers=FALLBACK_HEADERS, timeout=20, verify=False)
        if resp.status_code != 200:
            print(f"[fallback] HTTP {resp.status_code} для {law_key}")
            return ""
        soup = BeautifulSoup(resp.text, "html.parser")
        content = soup.select_one("div.document-text, div.law-text, article, #document") or soup
        full_text = content.get_text(separator="\n", strip=True)
        blocks = re.split(r"(?=Статья\s+\d+)", full_text)
        scored = []
        for block in blocks:
            block = block.strip()
            if len(block) < 80:
                continue
            num = _fallback_article_number(block)
            if num in _FALLBACK_BAD:
                continue
            if num in _FALLBACK_NEDRA and not any(w in ql for w in _NEDRA_WORDS):
                continue
            s = _fallback_score(block, query, law_key)
            if s <= 0:
                continue
            link = url + (f"#z{num}" if num else "")
            scored.append((s, block[:1800] + f"\nСсылка: {link}"))
        scored.sort(key=lambda x: x[0], reverse=True)
        return "\n\n".join(t for _, t in scored[:limit])
    except Exception as e:
        print(f"[fallback] Ошибка парсинга {law_key}: {e}")
        return ""


