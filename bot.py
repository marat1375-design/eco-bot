def build_context(query: str) -> str:
    """
    1. Берёт статьи из локальной базы.
    2. Если локальных статей < 3 — дополняет резервным парсингом adilet.zan.kz.
    """
    articles = select_articles(query)
    ecocode_parts = []
    koap_parts = []

    for a in articles:
        block = f"{a['title']}\n{a['text']}\nСсылка: {a['url']}"
        if "Экологический кодекс" in a["law"]:
            ecocode_parts.append(block)
        else:
            koap_parts.append(block)

    # Резерв: подключаем парсинг если локальных статей мало
    if len(articles) < 3:
        print(f"[fallback] Локальных: {len(articles)} — запускаю парсинг adilet.zan.kz")
        for law_key in ["ecocode", "koap"]:
            fb = _fetch_fallback(law_key, query)
            if fb:
                marker = "\n--- Дополнительно с adilet.zan.kz ---\n"
                if law_key == "ecocode":
                    ecocode_parts.append(marker + fb)
                else:
                    koap_parts.append(marker + fb)

    if not ecocode_parts and not koap_parts:
        return ""

    parts = []
    if ecocode_parts:
        parts.append(
            "=== Экологический кодекс РК от 02.01.2021 N 400-VI ===\n\n"
            + "\n\n".join(ecocode_parts)
        )
    if koap_parts:
        parts.append(
            "=== КоАП РК от 05.07.2014 N 235-V ===\n\n"
            + "\n\n".join(koap_parts)
        )
    return "\n\n".join(parts)


def is_ecology_query(text: str) -> bool:
    text_lower = text.lower()
    if any(kw in text_lower for kw in NON_ECO_KEYWORDS):
        return False
    return any(kw in text_lower for kw in ECO_KEYWORDS)


def clean_answer(text: str) -> str:
    if not text:
        return "Пустой ответ."
    text = text.replace("**", "")
    text = text.replace("\u00A0", " ")
    text = re.sub(r"(?m)^\s*#{1,6}\s+", "", text)
    text = re.sub(r"(?m)^\s*\*\s+", "- ", text)
    return text.strip()


def send_long_message(chat_id, text: str):
    text = clean_answer(text)
    for part in util.smart_split(text, chars_per_string=3000):
        bot.send_message(chat_id, part)


