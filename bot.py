def load_whitelist():
    """Загружает вайтлист из файла при старте."""
    global WHITELIST
    if os.path.exists(WHITELIST_FILE):
        try:
            with open(WHITELIST_FILE, "r", encoding="utf-8") as f:
                data = json.load(f)
            WHITELIST = {int(k): v for k, v in data.items()}
            print(f"[whitelist] Загружено {len(WHITELIST)} пользователей")
        except Exception as e:
            print(f"[whitelist] Ошибка загрузки: {e}")
    env_users = os.environ.get("ALLOWED_USERS", "")
    if env_users:
        added = 0
        for uid_str in env_users.split(","):
            try:
                uid = int(uid_str.strip())
                if uid not in WHITELIST:
                    WHITELIST[uid] = {"name": f"user_{uid}", "limit": DEFAULT_DAILY_LIMIT}
                    added += 1
            except ValueError:
                pass
        if added:
            print(f"[whitelist] Из ALLOWED_USERS добавлено: {added}")


def save_whitelist():
    """Сохраняет вайтлист в файл."""
    try:
        with open(WHITELIST_FILE, "w", encoding="utf-8") as f:
            json.dump({str(k): v for k, v in WHITELIST.items()}, f, ensure_ascii=False, indent=2)
    except Exception as e:
        print(f"[whitelist] Ошибка сохранения: {e}")


