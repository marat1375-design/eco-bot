MAX_IMAGE_SIZE = 1280

def convert_to_jpeg(photo_bytes: bytes) -> bytes:
    """Конвертирует фото в JPEG с ресайзом до MAX_IMAGE_SIZE px по длинной стороне."""
    try:
        img = Image.open(BytesIO(photo_bytes))
        img = img.convert("RGB")
        w, h = img.size
        if max(w, h) > MAX_IMAGE_SIZE:
            scale = MAX_IMAGE_SIZE / max(w, h)
            img = img.resize((int(w * scale), int(h * scale)), Image.LANCZOS)
        output = BytesIO()
        img.save(output, format="JPEG", quality=85)
        return output.getvalue()
    except Exception:
        return photo_bytes


def claude_generate(messages, max_tokens=4000, retries=3, delay=5, system=None):
    """Вызов Claude с автоматическим повтором при ошибке."""
    for attempt in range(retries):
        try:
            kwargs = dict(model=CLAUDE_MODEL, max_tokens=max_tokens, messages=messages)
            if system:
                kwargs["system"] = [{"type": "text", "text": system, "cache_control": {"type": "ephemeral"}}]
            response = claude.messages.create(**kwargs)
            return response.content[0].text
        except Exception as e:
            if attempt < retries - 1:
                print(f"[retry] Попытка {attempt + 1} не удалась: {e}. Жду {delay} сек...")
                time.sleep(delay)
            else:
                raise
