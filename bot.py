MAX_HISTORY = 6  # максимум сообщений на пользователя (3 пары user/assistant)
USER_HISTORY: dict = {}
_history_lock = threading.Lock()


def get_history(user_id: int) -> list:
    with _history_lock:
        return list(USER_HISTORY.get(user_id, []))


def add_to_history(user_id: int, role: str, content: str):
    with _history_lock:
        history = USER_HISTORY.setdefault(user_id, [])
        history.append({"role": role, "content": content})
        if len(history) > MAX_HISTORY:
            USER_HISTORY[user_id] = history[-MAX_HISTORY:]


def clear_history(user_id: int):
    with _history_lock:
        USER_HISTORY.pop(user_id, None)


def is_admin(user_id: int) -> bool:
    return user_id == ADMIN_ID


def is_allowed(user_id: int) -> bool:
    if is_admin(user_id):
        return True
    if os.environ.get("OPEN_ACCESS", "").lower() in ("1", "true", "yes"):
        return True
    return user_id in WHITELIST


def check_limit(user_id: int) -> bool:
    """True если лимит не исчерпан."""
    if is_admin(user_id):
        return True
    if user_id not in WHITELIST:
        return False
    today = str(date.today())
    counter = DAILY_COUNTERS.get(user_id, {"date": today, "count": 0})
    if counter["date"] != today:
        counter = {"date": today, "count": 0}
    limit = WHITELIST[user_id].get("limit", DEFAULT_DAILY_LIMIT)
    return counter["count"] < limit


def increment_counter(user_id: int):
    today = str(date.today())
    counter = DAILY_COUNTERS.get(user_id, {"date": today, "count": 0})
    if counter["date"] != today:
        counter = {"date": today, "count": 0}
    counter["count"] += 1
    DAILY_COUNTERS[user_id] = counter
    save_counters()


def get_remaining(user_id: int) -> int:
    if is_admin(user_id):
        return 9999
    today = str(date.today())
    counter = DAILY_COUNTERS.get(user_id, {"date": today, "count": 0})
    if counter["date"] != today:
        counter = {"date": today, "count": 0}
    limit = WHITELIST.get(user_id, {}).get("limit", DEFAULT_DAILY_LIMIT)
    return max(0, limit - counter["count"])


